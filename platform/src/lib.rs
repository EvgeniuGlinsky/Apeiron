//! Доступ к аппаратному хранилищу ключей платформы.
//!
//! Пока — заготовка под пред-полётную проверку сборки.

/// Имя платформы, под которую собран этот крейт.
pub fn platform_name() -> &'static str {
    if cfg!(target_os = "android") {
        "android"
    } else {
        "не android"
    }
}

/// Версия JNI, с которой собран крейт. Существует затем, чтобы зависимость
/// `jni` действительно компилировалась, а не просто числилась в манифесте.
#[cfg(target_os = "android")]
pub fn jni_version() -> i32 {
    jni::sys::JNI_VERSION_1_6
}
