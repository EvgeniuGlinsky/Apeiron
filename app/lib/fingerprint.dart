/// Раскладка отпечатка для экрана сверки.
///
/// Вынесено отдельно и покрыто тестами намеренно. Разбивка обязана быть
/// одинаковой на всех экранах: при сверке голосом плавающая раскладка —
/// источник ошибок, а ошибка здесь означает пропущенного посредника.
/// Падать этот экран тоже не имеет права — несверенный ключ равносилен
/// отсутствию защиты.
library;

/// Режет группы отпечатка на строки по [per] штук.
///
/// Последняя строка может быть неполной. Пустой вход даёт пустой результат.
/// При `per <= 0` возвращает одну строку со всеми группами, а не зацикливается.
List<List<String>> fingerprintRows(List<String> groups, int per) {
  if (groups.isEmpty) return const [];
  if (per <= 0) return [List.of(groups)];
  return [
    for (var i = 0; i < groups.length; i += per)
      groups.sublist(i, i + per > groups.length ? groups.length : i + per),
  ];
}
