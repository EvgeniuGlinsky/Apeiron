//! Пока — заготовка под пред-полётную проверку сборки.

/// Открывает базу по пути и возвращает версию SQLite.
///
/// Существует затем, чтобы связывание с SQLite действительно происходило:
/// неиспользуемая зависимость собралась бы, но не слинковалась, и отказ
/// обнаружился бы позже и в худшем месте.
pub fn sqlite_version() -> String {
    rusqlite::version().to_string()
}
